def normalize(text):
    """Приводит текст к виду для сравнения: без регистра, ё, лишних пробелов и точек в конце."""
    if text is None:
        return ""
    text = str(text).strip().lower().replace("ё", "е")
    text = re.sub(r"\s+", " ", text)
    return text.rstrip(".: ")


def header(short, max_score):
    return f"{short} (0-{max_score})"
